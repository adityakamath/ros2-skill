#!/usr/bin/env python3
"""Regenerate references/COMMANDS.md from the live argparse tree (never hand-edit that file)."""

import argparse
import os
import sys

from ros2_cli import build_parser

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "references", "COMMANDS.md")
HEADER = """# Command reference

Generated by `scripts/gen_commands_doc.py` from the CLI's argparse tree; do not edit by hand.
`CLI` means `python3 ${CLAUDE_SKILL_DIR}/scripts/ros2_cli.py`. Global options (before the command): `--timeout SECONDS`, `--retries N`. Every command prints JSON; run one to see its output shape.

"""


def _walk(parser, path, lines):
    subs = [a for a in parser._actions if isinstance(a, argparse._SubParsersAction)]
    if not subs:
        if path:
            lines.append("### CLI " + " ".join(path) + "\n\n```\n" + parser.format_help().rstrip() + "\n```\n")
        return
    for action in subs:
        seen = set()
        for name, sub in action.choices.items():
            if id(sub) in seen:  # skip aliases (ls, info, wtf, ...)
                continue
            seen.add(id(sub))
            _walk(sub, path + [name], lines)


def render():
    sys.argv[0] = "ros2_cli.py"  # argparse derives `prog` from argv[0]
    os.environ["COLUMNS"] = "100"
    lines = []
    _walk(build_parser(), [], lines)
    return HEADER + "\n".join(lines)


def main():
    text = render()
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
